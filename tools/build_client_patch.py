#!/usr/bin/env python3
"""
Build the classless client patch: client-patch/affix_dbc_rows.json and
dist/ItemAffixesPatch.zip.

    python3 tools/build_client_patch.py /path/to/server/data/dbc

The rows come from upstream's own generator, so they are exactly what
tools/patch_custom_spells.ps1 would put in the client: the script runs with
pwsh against a COPY of the server's Spell.dbc and SkillLineAbility.dbc in a
temporary folder (the server's files are never touched), and every record it
adds is extracted. Requires PowerShell 7 (pwsh).
"""
import argparse
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
CLIENT = os.path.join(ROOT, "client-patch")
DIST = os.path.join(ROOT, "dist")

# String columns per DBC (0-based field index). Spell.dbc: name, rank,
# description, tooltip, 16 locales each; the 17th column of each is a flag.
STRING_FIELDS = {
    "Spell.dbc": [*range(136, 152), *range(153, 169), *range(170, 186), *range(187, 203)],
    "SkillLineAbility.dbc": [],
}


def load_dbc(path):
    raw = open(path, "rb").read()
    magic, count, fields, size, strsize = struct.unpack_from("<4s4I", raw)
    if magic != b"WDBC":
        raise SystemExit("%s is not a DBC" % path)
    strings = raw[20 + count * size:]
    rows = {}
    for i in range(count):
        rec = struct.unpack_from("<%dI" % fields, raw, 20 + i * size)
        rows[rec[0]] = rec
    return rows, strings, fields


def cstr(block, offset):
    return block[offset:block.index(b"\0", offset)].decode("utf-8")


def new_rows(stock_path, patched_path, name):
    old, _, fields = load_dbc(stock_path)
    new, strings, fields2 = load_dbc(patched_path)
    if fields != fields2:
        raise SystemExit("%s: field count changed" % name)
    str_fields = set(STRING_FIELDS[name])
    out = []
    for rid in sorted(set(new) - set(old)):
        rec = new[rid]
        values = [0 if i in str_fields else v for i, v in enumerate(rec)]
        texts = {str(i): cstr(strings, rec[i]) for i in str_fields if rec[i]}
        out.append({"id": rid, "values": values, "strings": texts})
    changed = [rid for rid in old if rid in new and old[rid] != new[rid]]
    return {"fields": fields, "string_fields": sorted(str_fields), "rows": out}, changed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("server_dbc_dir")
    ap.add_argument("--no-zip", action="store_true")
    args = ap.parse_args()

    if not shutil.which("pwsh"):
        raise SystemExit("pwsh (PowerShell 7) not found")

    with tempfile.TemporaryDirectory() as tmp:
        stock = os.path.join(tmp, "stock")
        work = os.path.join(tmp, "dbc")
        data = os.path.join(tmp, "Data")
        os.makedirs(stock)
        os.makedirs(work)
        os.makedirs(os.path.join(data, "enUS"))
        for name in STRING_FIELDS:
            shutil.copy2(os.path.join(args.server_dbc_dir, name), stock)
            shutil.copy2(os.path.join(args.server_dbc_dir, name), work)

        env = dict(os.environ, SERVER_DBC_DIR=work, CLIENT_DATA_DIR=data,
                   PATCH_SUFFIX_SPELLS="Q", PATCH_SUFFIX_DBC="P")
        subprocess.run(["pwsh", "-NoLogo", "-NoProfile", "-File",
                        os.path.join(ROOT, "tools", "patch_custom_spells.ps1")],
                       env=env, check=True, stdout=subprocess.DEVNULL)

        result = {"_comment": "Generated by tools/build_client_patch.py from "
                              "imprints/custom_spells.json -- do not edit.",
                  "dbc": {}}
        for name in STRING_FIELDS:
            table, changed = new_rows(os.path.join(stock, name), os.path.join(work, name), name)
            if changed:
                raise SystemExit("%s: upstream script changed existing rows %s; "
                                 "the patcher only appends" % (name, changed[:10]))
            result["dbc"][name] = table
            print("  %-22s %d new row(s)" % (name, len(table["rows"])))

    os.makedirs(CLIENT, exist_ok=True)
    rows_path = os.path.join(CLIENT, "affix_dbc_rows.json")
    with open(rows_path, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(result, fh, indent=1, ensure_ascii=False)
        fh.write("\n")
    print("  wrote %s" % os.path.relpath(rows_path, ROOT))

    if args.no_zip:
        return 0

    os.makedirs(DIST, exist_ok=True)
    zip_path = os.path.join(DIST, "ItemAffixesPatch.zip")
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for name in ("ItemAffixesPatch.py", "ItemAffixesPatch.bat", "ItemAffixesPatch.sh",
                     "affix_dbc_rows.json", "README.md"):
            zf.write(os.path.join(CLIENT, name), "ItemAffixesPatch/" + name)
        for addon in ("ItemAffixes", "ItemAffixesToast"):
            base = os.path.join(ROOT, "addon", addon)
            if not os.path.isdir(base):
                continue
            for dirpath, _dirs, files in os.walk(base):
                for f in sorted(files):
                    full = os.path.join(dirpath, f)
                    rel = os.path.relpath(full, os.path.join(ROOT, "addon"))
                    zf.write(full, "ItemAffixesPatch/AddOns/" + rel.replace(os.sep, "/"))
    print("  wrote %s" % os.path.relpath(zip_path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
